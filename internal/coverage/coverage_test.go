// Generated code arrives in large, entirely-uncovered blocks nobody is going
// to hand-test. Left in the denominator it dominates the aggregate: wardnet's
// generated REST client alone drags its SDK module to 2%.
func TestGoProfileLinesExcludeGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	generated := "// Code generated by openapi-codegen. DO NOT EDIT.\n" +
		"\npackage rest\n\nfunc Gen() {\n\tprintln(1)\n}\n"
	if err := os.WriteFile(filepath.Join(dir, "rest.gen.go"), []byte(generated), 0o600); err != nil {
		t.Fatal(err)
	}
	handWritten := "package rest\n\nfunc Hand() {\n\tprintln(1)\n}\n"
	if err := os.WriteFile(filepath.Join(dir, "hand.go"), []byte(handWritten), 0o600); err != nil {
		t.Fatal(err)
	}
	// The generated file is entirely uncovered and the hand-written one
	// covered: counting both would give 50%, only the latter counts.
	profile := "mode: set\n" +
		"fixture/rest.gen.go:5.13,7.2 1 0\n" +
		"fixture/hand.go:3.14,5.2 1 1\n"
	path := filepath.Join(dir, "cover.out")
	if err := os.WriteFile(path, []byte(profile), 0o600); err != nil {
		t.Fatal(err)
	}

	got, ok := goProfileLines(GoModuleProfile{Profile: path, ModuleName: "fixture"}, dir)
	if !ok || got.Percent() != 100 {
		t.Fatalf("goProfileLines = (%+v, %v), want 100%%, true", got, ok)
	}
}

