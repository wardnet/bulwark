// The percentage comes from the profile itself rather than `go tool cover
// -func`, which only runs from inside the module a profile came from — see
// goProfilePercent's doc comment.
func TestGoProfilePercent(t *testing.T) {
	dir := t.TempDir()
	// 3 of 4 statements covered.
	profile := "mode: set\n" +
		"fixture/main.go:3.13,5.2 2 1\n" +
		"fixture/main.go:7.13,7.20 1 3\n" +
		"fixture/main.go:9.13,9.20 1 0\n"
	path := filepath.Join(dir, "cover.out")
	if err := os.WriteFile(path, []byte(profile), 0o600); err != nil {
		t.Fatal(err)
	}

	got, ok := goProfilePercent(GoModuleProfile{Profile: path, ModuleName: "fixture"}, dir)
	if !ok || got != 75 {
		t.Fatalf("goProfilePercent = (%v, %v), want (75, true)", got, ok)
	}
}

