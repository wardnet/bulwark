// TestGoCoverageSourceReportDoesNotRunTests guards SourceReport's core
// promise: it must parse an existing profile without ever invoking `go test`.
// A fixture Go module with a deliberately failing test proves this — if
// goCoverage under SourceReport ran the tests, the run would fail/hang and
// this test would fail with it; instead it should cleanly read the
// pre-existing profile.
//
// This is the same guarantee the old TestGoCoverageModeSkipDoesNotRunTests
// held, under the renamed axis. Renaming "skip the tests" to "a report is the
// source" changes who the setting is addressed to, not what bulwark does with
// it: the never-execute promise is what makes a report-sourced repo's CI
// budget predictable, so it survives the rename verbatim.
func TestGoCoverageSourceReportDoesNotRunTests(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "go.mod", "module fixture\n\ngo 1.26\n")
	write(t, dir, "main.go", "package fixture\n\nfunc Foo() {}\n")
	write(t, dir, "main_test.go", "package fixture\n\nimport \"testing\"\n\nfunc TestFails(t *testing.T) { t.Fatal(\"this test must never run under SourceReport\") }\n")
	write(t, dir, "coverage.out", "mode: set\nfixture/main.go:3.13,3.16 1 1\n")

	units, _, ok := goCoverage(context.Background(), dir, "", SourceReport, nil, nil)
	if !ok {
		t.Fatal("expected goCoverage to succeed by parsing the existing coverage.out")
	}
	if got := aggregate(units).Percent(); got != 100 {
		t.Fatalf("got %v%%, want 100%% from the fixture profile", got)
	}
}

// The regression this whole change exists for: a monorepo whose Go modules
// live in subdirectories, with module paths resembling neither each other nor
// their own directories — wardnet's `github.com/wardnet/wardnet/source/wctl`
// under `wctl/` and `wardnet.network/go` under `sdk/wardnet-go/`.
//
// bulwark used to treat --dir as the one module: it ran `go test`, `go list
// -m` and `go tool cover -func` there, all of which need a module root, so Go
// coverage silently measured nothing and the language vanished from the gate
// entirely. Both modules must now be discovered, measured, and reported with
// enough per-module detail to map their profiles back onto --dir-relative
// paths.
func TestGoCoverageDiscoversEveryModuleUnderDir(t *testing.T) {
	dir := t.TempDir()
	writeNested(t, dir, filepath.Join("wctl", "go.mod"), "module github.com/wardnet/wardnet/source/wctl\n\ngo 1.26\n")
	writeNested(t, dir, filepath.Join("wctl", "main.go"), "package wctl\n\nfunc Foo() {}\n")
	// Fully covered.
	writeNested(t, dir, filepath.Join("wctl", "coverage.out"),
		"mode: set\ngithub.com/wardnet/wardnet/source/wctl/main.go:3.13,3.16 1 1\n")

	writeNested(t, dir, filepath.Join("sdk", "wardnet-go", "go.mod"), "module wardnet.network/go\n\ngo 1.26\n")
	writeNested(t, dir, filepath.Join("sdk", "wardnet-go", "api.go"), "package api\n\nfunc Bar() {}\n")
	// Entirely uncovered, so a figure spanning both modules is unmistakable.
	writeNested(t, dir, filepath.Join("sdk", "wardnet-go", "coverage.out"),
		"mode: set\nwardnet.network/go/api.go:3.13,3.16 1 0\n")

	units, profiles, ok := goCoverage(context.Background(), dir, "", SourceReport, nil, nil)
	if !ok {
		t.Fatal("goCoverage found no measurable Go module under a dir holding two")
	}
	if len(profiles) != 2 {
		t.Fatalf("measured %d module(s), want 2: %+v", len(profiles), profiles)
	}
	// One statement each, so equal weight: 1 of 2 statements covered.
	if got := aggregate(units).Percent(); got != 50 {
		t.Fatalf("got %v%%, want 50%% (1 of 2 statements across the two modules)", got)
	}

	// Each module carries its own path and directory: one global module name
	// could only ever resolve one of these, which is the bug.
	byRelDir := map[string]GoModuleProfile{}
	for _, src := range profiles {
		byRelDir[filepath.ToSlash(src.RelDir)] = src
	}
	if got := byRelDir["wctl"].ModuleName; got != "github.com/wardnet/wardnet/source/wctl" {
		t.Errorf("wctl module name = %q", got)
	}
	if got := byRelDir["sdk/wardnet-go"].ModuleName; got != "wardnet.network/go" {
		t.Errorf("sdk module name = %q", got)
	}
}

