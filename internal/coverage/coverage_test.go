// The units a language's figure is summed from also leave Compute, so a
// caller can gate on the distribution the aggregate deliberately hides. Each
// carries its own directory relative to dir and its own counts.
func TestComputeReturnsPerUnitCounts(t *testing.T) {
	dir := t.TempDir()
	writeNested(t, dir, filepath.Join("packages", "lib", "package.json"), `{"name":"lib"}`)
	writeNested(t, dir, filepath.Join("packages", "lib", "coverage", "coverage-summary.json"),
		`{"total":{"lines":{"total":100,"covered":90,"skipped":0,"pct":90}}}`)
	writeNested(t, dir, filepath.Join("packages", "layout", "package.json"), `{"name":"layout"}`)
	writeNested(t, dir, filepath.Join("packages", "layout", "coverage", "coverage-summary.json"),
		`{"total":{"lines":{"total":8,"covered":0,"skipped":0,"pct":0}}}`)

	report, units, _, cleanup, err := Compute(context.Background(), dir, config.Default(), SourceReport, ReportPaths{}, PatchWanted{})
	defer cleanup()
	if err != nil {
		t.Fatal(err)
	}
	const want = 90.0 / 108 * 100
	if got := report["typescript"]; math.Abs(got-want) > 1e-9 {
		t.Errorf("typescript = %.4f%%, want %.4f%%", got, want)
	}
	byDir := map[string]LineCount{}
	for _, u := range units {
		if u.Lang != "typescript" {
			t.Errorf("unit %+v: unexpected language", u)
		}
		byDir[filepath.ToSlash(u.Dir)] = u.Lines
	}
	// The untested package is 0.1% of the aggregate and invisible there. It
	// is a unit at 0% here, which is the whole reason the units are returned.
	if got := byDir["packages/layout"]; got != (LineCount{Covered: 0, Total: 8}) {
		t.Errorf("packages/layout = %+v, want {0 8}", got)
	}
	if got := byDir["packages/lib"]; got != (LineCount{Covered: 90, Total: 100}) {
		t.Errorf("packages/lib = %+v, want {90 100}", got)
	}
}

// A discovered unit whose report is missing is returned with a zero LineCount
// rather than dropped, so the caller's per-unit floor can name it. Dropping it
// would leave the floor gate silently covering fewer units than the repo holds
// while the language still reported a percentage — and the per-language
// unmeasured warning cannot see that, because the language did measure.
func TestGoCoverageReturnsUnmeasuredModules(t *testing.T) {
	dir := t.TempDir()
	writeNested(t, dir, filepath.Join("measured", "go.mod"), "module fixture/measured\n\ngo 1.26\n")
	writeNested(t, dir, filepath.Join("measured", "main.go"), "package measured\n")
	writeNested(t, dir, filepath.Join("measured", "coverage.out"),
		"mode: set\nfixture/measured/main.go:3.13,5.2 4 1\n")
	// Discovered, but with no profile for SourceReport to read.
	writeNested(t, dir, filepath.Join("skipped", "go.mod"), "module fixture/skipped\n\ngo 1.26\n")
	writeNested(t, dir, filepath.Join("skipped", "main.go"), "package skipped\n")

	units, _, ok := goCoverage(context.Background(), dir, "", SourceReport, nil, nil)
	if !ok {
		t.Fatal("one module measured, so goCoverage must report the language")
	}
	byDir := map[string]Unit{}
	for _, u := range units {
		byDir[filepath.ToSlash(u.Dir)] = u
	}
	if u, present := byDir["skipped"]; !present || u.Measured() {
		t.Errorf("skipped module = %+v (present %v), want present and unmeasured", u, present)
	}
	if u := byDir["measured"]; !u.Measured() {
		t.Errorf("measured module = %+v, want measured", u)
	}
	// The unmeasured module contributes nothing — not a zero that would drag
	// the language's figure down.
	if got := aggregate(units).Percent(); got != 100 {
		t.Errorf("aggregate = %v%%, want 100%% — an unmeasured unit must not count as 0/0 or 0%%", got)
	}
}

// A package that declares no test:coverage script has opted out of being
// measured — a different state from a report bulwark expected and did not
// find. It must not become an unmeasured Unit: a types-only or config-only
// package in a monorepo would then produce an [UNMEASURED] line and a stderr
// warning on every run, in every PR comment.
func TestTSCoverageSkipsPackagesWithoutACoverageScript(t *testing.T) {
	dir := t.TempDir()
	writeNested(t, dir, filepath.Join("packages", "app", "package.json"),
		`{"name":"app","scripts":{"test:coverage":"true"}}`)
	writeNested(t, dir, filepath.Join("packages", "app", "coverage", "coverage-summary.json"),
		`{"total":{"lines":{"total":100,"covered":90,"skipped":0,"pct":90}}}`)
	// Declares no test:coverage script at all.
	writeNested(t, dir, filepath.Join("packages", "types", "package.json"), `{"name":"types"}`)

	units, ok := tsCoverage(context.Background(), dir, nil, SourceRun, "")
	if !ok {
		t.Fatal("the package with a coverage script measured, so tsCoverage must report typescript")
	}
	for _, u := range units {
		if strings.Contains(filepath.ToSlash(u.Dir), "types") {
			t.Errorf("a package with no test:coverage script became a unit: %+v", u)
		}
	}
	if len(units) != 1 {
		t.Errorf("got %d unit(s), want only the package that declares a coverage script: %+v", len(units), units)
	}
}

// The opt-out rule has to hold under SourceReport too, which is the mode CI
// uses. A types-only or config-only package produces no report there either,
// and treating that as unmeasured would print an [UNMEASURED] floor line and a
// stderr warning for it on every run and in every PR comment.
//
// A report that is present still wins: a workspace-level runner can write into
// a package that declares no script of its own, and that package is measured,
// not opted out.
func TestTSCoverageSourceReportSkipsPackagesWithoutACoverageScript(t *testing.T) {
	dir := t.TempDir()
	writeNested(t, dir, filepath.Join("packages", "app", "package.json"),
		`{"name":"app","scripts":{"test:coverage":"true"}}`)
	writeNested(t, dir, filepath.Join("packages", "app", "coverage", "coverage-summary.json"),
		`{"total":{"lines":{"total":100,"covered":90,"skipped":0,"pct":90}}}`)
	// Declares a script but produced no report: genuinely unmeasured.
	writeNested(t, dir, filepath.Join("packages", "broken", "package.json"),
		`{"name":"broken","scripts":{"test:coverage":"true"}}`)
	// Declares nothing and produced nothing: opted out.
	writeNested(t, dir, filepath.Join("packages", "types", "package.json"), `{"name":"types"}`)
	// Declares nothing but a workspace runner wrote its report: measured.
	writeNested(t, dir, filepath.Join("packages", "shared", "package.json"), `{"name":"shared"}`)
	writeNested(t, dir, filepath.Join("packages", "shared", "coverage", "coverage-summary.json"),
		`{"total":{"lines":{"total":50,"covered":25,"skipped":0,"pct":50}}}`)

	units, ok := tsCoverage(context.Background(), dir, nil, SourceReport, "")
	if !ok {
		t.Fatal("tsCoverage measured nothing")
	}
	got := map[string]bool{}
	for _, u := range units {
		got[filepath.ToSlash(u.Dir)] = u.Measured()
	}
	for dir, wantMeasured := range map[string]bool{
		"packages/app":    true,
		"packages/shared": true,
		"packages/broken": false,
	} {
		measured, present := got[dir]
		if !present {
			t.Errorf("%s missing from the units", dir)
			continue
		}
		if measured != wantMeasured {
			t.Errorf("%s measured = %v, want %v", dir, measured, wantMeasured)
		}
	}
	if _, present := got["packages/types"]; present {
		t.Errorf("packages/types declares no coverage script and produced no report — it opted out, but became a unit: %+v", units)
	}
}
