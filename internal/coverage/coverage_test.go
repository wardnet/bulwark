// The asymmetry the line-weighted aggregate exists for: a language's figure
// must be its units' summed counts, not the mean of their percentages. A mean
// gives a 4-statement module the same vote as a 100-statement one, so a
// single small, poorly-tested unit drags the headline down by tens of points
// while barely changing how much code is actually untested.
//
// Both directions are checked, because a mean is wrong symmetrically: it
// understates a repo whose small unit is the bad one, and overstates a repo
// whose small unit is the good one.
func TestGoCoverageWeightsModulesByStatementCount(t *testing.T) {
	for _, tc := range []struct {
		name                 string
		bigCount, bigHits    int
		smallCount, smallHit int
		want                 float64
	}{
		// 100/100 and 0/4 — the mean says 50%, the lines say 96.15%.
		{name: "small unit poorly covered", bigCount: 100, bigHits: 1, smallCount: 4, smallHit: 0, want: 100.0 / 104 * 100},
		// 0/100 and 4/4 — the mean says 50%, the lines say 3.85%.
		{name: "small unit well covered", bigCount: 100, bigHits: 0, smallCount: 4, smallHit: 1, want: 4.0 / 104 * 100},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			writeNested(t, dir, filepath.Join("big", "go.mod"), "module fixture/big\n\ngo 1.26\n")
			writeNested(t, dir, filepath.Join("big", "main.go"), "package big\n")
			writeNested(t, dir, filepath.Join("big", "coverage.out"),
				fmt.Sprintf("mode: set\nfixture/big/main.go:3.13,50.2 %d %d\n", tc.bigCount, tc.bigHits))

			writeNested(t, dir, filepath.Join("small", "go.mod"), "module fixture/small\n\ngo 1.26\n")
			writeNested(t, dir, filepath.Join("small", "main.go"), "package small\n")
			writeNested(t, dir, filepath.Join("small", "coverage.out"),
				fmt.Sprintf("mode: set\nfixture/small/main.go:3.13,7.2 %d %d\n", tc.smallCount, tc.smallHit))

			units, _, ok := goCoverage(context.Background(), dir, "", SourceReport, nil, nil)
			if !ok {
				t.Fatal("goCoverage measured neither module")
			}
			if got := aggregate(units).Percent(); math.Abs(got-tc.want) > 1e-9 {
				t.Errorf("aggregate = %.4f%%, want %.4f%% — an unweighted mean of the two would give 50%%", got, tc.want)
			}
		})
	}
}

// Rust carries the same rule as Go: a workspace of one tiny helper crate and
// one large one has a single honest line-coverage figure, and it is not the
// mean of the two.
func TestRustCoverageWeightsCratesByLineCount(t *testing.T) {
	dir := t.TempDir()
	writeNested(t, dir, filepath.Join("big", "Cargo.toml"), "[package]\nname = \"big\"\nversion = \"0.1.0\"\n")
	writeNested(t, dir, filepath.Join("big", "coverage", "llvm-cov.json"),
		`{"data":[{"totals":{"lines":{"count":5000,"covered":5000,"percent":100}}}]}`)
	writeNested(t, dir, filepath.Join("small", "Cargo.toml"), "[package]\nname = \"small\"\nversion = \"0.1.0\"\n")
	writeNested(t, dir, filepath.Join("small", "coverage", "llvm-cov.json"),
		`{"data":[{"totals":{"lines":{"count":10,"covered":0,"percent":0}}}]}`)

	units, _, ok := rustCoverage(context.Background(), dir, "", SourceReport, nil, nil, nil, false)
	if !ok {
		t.Fatal("rustCoverage measured neither crate")
	}
	if len(units) != 2 {
		t.Fatalf("measured %d crate(s), want 2: %+v", len(units), units)
	}
	const want = 5000.0 / 5010 * 100 // 99.80%, against an unweighted mean of 50%
	if got := aggregate(units).Percent(); math.Abs(got-want) > 1e-9 {
		t.Errorf("aggregate = %.4f%%, want %.4f%% — an unweighted mean of the two would give 50%%", got, want)
	}
}

