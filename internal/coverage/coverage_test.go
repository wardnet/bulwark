func TestLlvmCovExportParsing(t *testing.T) {
	data := []byte(`{"data":[{"totals":{"lines":{"count":100,"covered":87,"percent":87.3}}}]}`)
	var export llvmCovExport
	if err := json.Unmarshal(data, &export); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}
	// count/covered, not percent: the counts are what a language's figure is
	// summed from, and a percentage cannot be summed without losing the
	// unit's size.
	if len(export.Data) != 1 || export.Data[0].Totals.Lines.Count != 100 || export.Data[0].Totals.Lines.Covered != 87 {
		t.Fatalf("got %+v, want count 100 covered 87", export)
	}
}

